
import os
from contextlib import asynccontextmanager

import psycopg
from psycopg.rows import dict_row
from psycopg.errors import UniqueViolation

from fastapi import FastAPI, HTTPException
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel, Field


def get_connection():
    database_url = os.getenv("DATABASE_URL")

    if not database_url:
        raise RuntimeError("DATABASE_URL environment variable is not set")

    return psycopg.connect(
        database_url,
        row_factory=dict_row
    )


def initialize_database():
    with get_connection() as connection:
        connection.execute("""
            CREATE TABLE IF NOT EXISTS products (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                name TEXT NOT NULL,
                category TEXT NOT NULL,
                sku TEXT NOT NULL UNIQUE,
                stock INTEGER NOT NULL DEFAULT 0,
                unit TEXT NOT NULL DEFAULT 'units',
                expiry TEXT NOT NULL,
                demand DOUBLE PRECISION NOT NULL DEFAULT 0,
                cost DOUBLE PRECISION NOT NULL DEFAULT 0
            )
        """)


@asynccontextmanager
async def lifespan(app: FastAPI):
    initialize_database()
    yield


app = FastAPI(
    title="FreshStock AI API",
    description="Inventory management backend for grocery and medical stores",
    version="1.0.0",
    lifespan=lifespan,
)


app.add_middleware(
    CORSMiddleware,
    allow_origins=[
        "http://localhost:5173",
        "http://127.0.0.1:5173",
        "https://mdc-aiml-1.onrender.com",
    ],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)


class ProductCreate(BaseModel):
    name: str = Field(min_length=1, max_length=150)
    category: str = Field(min_length=1, max_length=80)
    sku: str = Field(min_length=1, max_length=80)
    stock: int = Field(ge=0)
    unit: str = Field(min_length=1, max_length=30)
    expiry: str
    demand: float = Field(default=0, ge=0)
    cost: float = Field(default=0, ge=0)


@app.get("/")
def home():
    return {
        "message": "FreshStock AI backend is running!",
        "docs": "/docs",
    }


@app.get("/health")
def health():
    return {"status": "healthy"}


@app.get("/products")
def get_products():
    with get_connection() as connection:
        rows = connection.execute(
            "SELECT * FROM products ORDER BY id DESC"
        ).fetchall()

    return rows


@app.post("/products", status_code=201)
def create_product(product: ProductCreate):
    try:
        with get_connection() as connection:
            row = connection.execute(
                """
                INSERT INTO products
                (name, category, sku, stock, unit, expiry, demand, cost)
                VALUES (%s, %s, %s, %s, %s, %s, %s, %s)
                RETURNING *
                """,
                (
                    product.name.strip(),
                    product.category,
                    product.sku.strip(),
                    product.stock,
                    product.unit,
                    product.expiry,
                    product.demand,
                    product.cost,
                ),
            ).fetchone()

        return row

    except UniqueViolation:
        raise HTTPException(
            status_code=409,
            detail="This SKU already exists. Use a unique product code.",
        )


@app.put("/products/{product_id}")
def update_product(product_id: int, product: ProductCreate):
    try:
        with get_connection() as connection:
            row = connection.execute(
                """
                UPDATE products
                SET name=%s, category=%s, sku=%s, stock=%s,
                    unit=%s, expiry=%s, demand=%s, cost=%s
                WHERE id=%s
                RETURNING *
                """,
                (
                    product.name.strip(),
                    product.category,
                    product.sku.strip(),
                    product.stock,
                    product.unit,
                    product.expiry,
                    product.demand,
                    product.cost,
                    product_id,
                ),
            ).fetchone()

            if row is None:
                raise HTTPException(
                    status_code=404,
                    detail="Product not found",
                )

        return row

    except UniqueViolation:
        raise HTTPException(
            status_code=409,
            detail="This SKU already belongs to another product.",
        )


@app.delete("/products/{product_id}")
def delete_product(product_id: int):
    with get_connection() as connection:
        row = connection.execute(
            "DELETE FROM products WHERE id=%s RETURNING id",
            (product_id,),
        ).fetchone()

        if row is None:
            raise HTTPException(
                status_code=404,
                detail="Product not found",
            )

    return {"message": "Product deleted successfully"}


@app.get("/dashboard")
def dashboard():
    with get_connection() as connection:
        result = connection.execute("""
            SELECT
                COUNT(*) AS total_products,
                COALESCE(SUM(stock), 0) AS total_units,
                COALESCE(SUM(CASE WHEN stock < 30 THEN 1 ELSE 0 END), 0)
                    AS low_stock_items
            FROM products
        """).fetchone()

    return result


@app.get("/ml-forecast")
def get_ml_forecast():
    import pandas as pd
    from pathlib import Path

    file_path = Path(__file__).parent / "forecast_output.csv"

    if not file_path.exists():
        raise HTTPException(
            status_code=404,
            detail="ML forecast file not found. Train the model first."
        )

    df = pd.read_csv(file_path)

    return df.to_dict(orient="records")
